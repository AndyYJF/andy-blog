/**
 * Emit candidate-nginx.conf / candidate-staging-nginx.conf for isolated
 * `nginx -t -c`, plus a full staging-http.conf for new.andy-y.cn.
 *
 * Staging maps use $staging_* names only — never overwrite production $legacy_*.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STAGING_SITE = 'https://new.andy-y.cn';

const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i === -1 ? null : process.argv[i + 1];
};

const releaseId = arg('--release-id');
const outDir = arg('--out');
if (!releaseId || !outDir) throw new Error('--release-id and --out required');

const escapeNginx = (value) =>
  String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');

const escapeNginxRegex = (value) =>
  String(value).replace(/[\\.^$|?*+()[\]{}]/g, '\\$&');

const buildMap = (varExpr, mapVar, entries, { boolean = false, caseSensitive = false } = {}) => {
  const lines = [`map ${varExpr} $${mapVar} {`, `  default ${boolean ? '0;' : '"";'}`];
  for (const [key, value] of entries) {
    const left = caseSensitive ? `~^${escapeNginxRegex(key)}$` : `"${escapeNginx(key)}"`;
    if (boolean) lines.push(`  ${left} 1;`);
    else lines.push(`  ${left} "${escapeNginx(value)}";`);
  }
  lines.push('}');
  return lines.join('\n');
};

const legacy = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/legacy-url-map.json'), 'utf8'));

const pathRedirect = [];
const queryRedirect = [];
const pathNotFound = [];
const pathGone = [];
const queryNotFound = [];
const queryGone = [];

for (const entry of legacy) {
  if (entry.action === 'redirect') {
    if (entry.queryKey) queryRedirect.push([entry.queryKey, entry.targetPath]);
    else if (entry.oldPath) pathRedirect.push([entry.oldPath, entry.targetPath]);
    continue;
  }
  if (entry.action === 'not_found') {
    if (entry.queryKey) queryNotFound.push([entry.queryKey, true]);
    else pathNotFound.push([entry.oldPath, true]);
    continue;
  }
  if (entry.action === 'gone') {
    if (entry.queryKey) queryGone.push([entry.queryKey, true]);
    else pathGone.push([entry.oldPath, true]);
  }
}

pathRedirect.sort((a, b) => a[0].localeCompare(b[0]));
queryRedirect.sort((a, b) => a[0].localeCompare(b[0]));

const stagingAction = `  if ($staging_query_not_found) { return 404; }
  if ($staging_not_found)       { return 404; }
  if ($staging_query_gone)      { return 410; }
  if ($staging_gone)            { return 410; }
  if ($staging_legacy_query_target != "") { return 302 ${STAGING_SITE}$staging_legacy_query_target; }
  if ($staging_legacy_target != "")       { return 302 ${STAGING_SITE}$staging_legacy_target; }`;

const maps = [
  buildMap('$uri', 'staging_legacy_target', pathRedirect, { caseSensitive: true }),
  buildMap('"$uri:$arg_p"', 'staging_legacy_query_target', queryRedirect),
  buildMap('$uri', 'staging_not_found', pathNotFound, { boolean: true, caseSensitive: true }),
  buildMap('$uri', 'staging_gone', pathGone, { boolean: true, caseSensitive: true }),
  buildMap('"$uri:$arg_p"', 'staging_query_not_found', queryNotFound, { boolean: true }),
  buildMap('"$uri:$arg_p"', 'staging_query_gone', queryGone, { boolean: true }),
].join('\n\n');

const stagingHttp = `# Generated by scripts/generate-candidate-nginx.js — do not edit by hand.
# Independent staging maps for new.andy-y.cn (never overwrite $legacy_*).
# path=${pathRedirect.length} query=${queryRedirect.length}

${maps}

server {
  listen 80;
  server_name new.andy-y.cn;
  add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
${stagingAction}
  return 301 ${STAGING_SITE}$request_uri;
}

server {
  listen 443 ssl;
  http2 on;
  server_name new.andy-y.cn;
  ssl_certificate     /etc/letsencrypt/live/new.andy-y.cn/fullchain.pem;
  ssl_certificate_key /etc/letsencrypt/live/new.andy-y.cn/privkey.pem;
  root /var/www/andy-y.cn/candidate/site;
  add_header X-Robots-Tag "noindex, nofollow, noarchive" always;

  gzip on;
  gzip_types text/css application/javascript application/json image/svg+xml application/xml+rss;
  gzip_min_length 1024;

${stagingAction}

  location ^~ /api/ {
    proxy_pass http://waline-staging:8360;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header Connection "";
    proxy_read_timeout 30s;
    add_header Cache-Control "no-store" always;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
  }
  location = /ui { return 308 /ui/; }
  location ^~ /ui/ {
    proxy_pass http://waline-staging:8360;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    add_header Cache-Control "no-store" always;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
  }

  location ^~ /_astro/ {
    try_files $uri =404;
    expires 1y;
    add_header Cache-Control "public, max-age=31536000, immutable";
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
  }

  location = /__release {
    try_files /release-id.txt =503;
    add_header Cache-Control "no-store" always;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
  }

  location / {
    try_files $uri $uri/index.html =404;
    add_header Cache-Control "public, max-age=0, s-maxage=600, must-revalidate" always;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
  }
}
`;

const releaseRoot = `/var/www/andy-y.cn/releases/${releaseId}`;
const body = (includeStaging) => `events {
  worker_connections 1024;
}
http {
  include /etc/nginx/mime.types;
  default_type application/octet-stream;
  sendfile on;
  # Isolated test entry: no conf.d directory and no current symlink.
  include ${releaseRoot}/nginx/release-http.conf;
${includeStaging ? `  include ${releaseRoot}/nginx/staging-http.conf;\n` : ''}}
`;

const abs = path.isAbsolute(outDir) ? outDir : path.join(ROOT, outDir);
fs.mkdirSync(abs, { recursive: true });
fs.writeFileSync(path.join(abs, 'candidate-nginx.conf'), body(false));
fs.writeFileSync(path.join(abs, 'candidate-staging-nginx.conf'), body(true));
fs.writeFileSync(path.join(abs, 'staging-http.conf'), stagingHttp);
console.error(`candidate nginx configs -> ${abs}`);
